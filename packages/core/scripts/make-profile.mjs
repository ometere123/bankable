// Generates the renderer profile manifest (spec 5.2) and the generated TS module the web app and CLI import.
// The manifest commits to: renderer source hashes, locked dependency integrity, fonts, QR parameters and the fixed verifier origin.
// It deliberately excludes generated constants and final fixture hashes (avoids self-reference).
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const repo = path.resolve(root, "../..");
const origin = (process.env.BANKABLE_ORIGIN || "https://bankable.invalid").replace(/\/$/, "");
const sha = (b) => "0x" + crypto.createHash("sha256").update(b).digest("hex");

const SOURCES = ["src/render/pdf.ts", "src/render/format.ts", "src/render/qr.ts", "src/canonical.ts", "src/ledger.ts"];
const files = {};
for (const f of SOURCES) files[f] = sha(fs.readFileSync(path.join(root, f)));

// dependency integrity strings straight from the lockfile (pnpm-lock.yaml 'packages:' section)
const lock = fs.readFileSync(path.join(repo, "pnpm-lock.yaml"), "utf8");
const want = ["pdf-lib", "@pdf-lib/standard-fonts", "@pdf-lib/upng", "pako", "qrcode-generator", "ethers"];
const dependencies = {};
for (const w of want) {
  const re = new RegExp(`^  '?${w.replace("/", "\\/")}@([0-9][^':]*)'?:\\n    resolution: \\{integrity: ([^,}]+)`, "gm");
  let m, found = false;
  while ((m = re.exec(lock))) { dependencies[`${w}@${m[1]}`] = m[2]; found = true; }
  if (!found) throw new Error(`dependency ${w} not found in pnpm-lock.yaml`);
}
const manifest = {
  profile: "bankable-renderer/1",
  origin,
  template: { files },
  dependencies: Object.fromEntries(Object.entries(dependencies).sort(([a], [b]) => (a < b ? -1 : 1))),
  fonts: { family: ["Helvetica", "Helvetica-Bold", "Courier"], embedded: false },
  qr: { library: "qrcode-generator", errorCorrection: "M", mode: "Byte" },
};
const text = JSON.stringify(manifest, null, 2) + "\n";
fs.mkdirSync(path.join(root, "profiles"), { recursive: true });
fs.writeFileSync(path.join(root, "profiles/renderer-1.json"), text);
fs.writeFileSync(path.join(root, "src/profiles.generated.ts"),
  `// GENERATED by scripts/make-profile.mjs. Do not edit. rendererId = keccak256(manifest bytes).\nexport const PROFILE_MANIFESTS: string[] = [${JSON.stringify(text)}];\n`);
console.log("profile written; origin =", origin);
